function getBot(id) {
  if (!id) return null;
  const key = id.toLowerCase().replace('bot_', '');
  return BOTS[key] || null;
}

function getRandomBot() {
  const keys = Object.keys(BOTS);
  const randomKey = keys[Math.floor(Math.random() * keys.length)];
  return BOTS[randomKey];
}

function getAllBotsList() {
  return Object.values(BOTS).map(b => ({
    id: b.id,
    name: b.name,
    title: b.title,
    avatar: b.avatar,
    difficulty: b.difficulty,
    description: b.description,
    elements: b.characterCard.elements,
    clan: b.characterCard.clan,
    chakra: b.characterCard.chakra,
    speed: b.characterCard.speed,
    reaction: b.characterCard.reaction,
    eye: b.characterCard.eye ? b.characterCard.eye.name : null
  }));
}

