export function getDojutsuById(id) {
  if (!id) return DOJUTSU_OPTIONS[0];
  const found = DOJUTSU_OPTIONS.find(d => d.id === id);
  if (found) return found;
  // Поиск по подстроке ID или названию
  const sub = DOJUTSU_OPTIONS.find(d => 
    id.toLowerCase().includes(d.id.toLowerCase()) || 
    d.name.toLowerCase().includes(id.toLowerCase())
  );
  return sub || DOJUTSU_OPTIONS[0];
}
