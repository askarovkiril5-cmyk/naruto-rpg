/**
 * Расчет эффективных боевых статов шиноби с учетом додзюцу по канону Раздела 1 и Раздела 3
 * @param {object} baseStats - { speed, reaction, clan, clans, isEyeActive, hasBlindSpot, isUnderGenjutsu }
 * @param {object|string} dojutsu - объект или ID додзюцу
 */
function calculateEffectiveStats(baseStats = {}, dojutsu = null, isEyeActive = true) {
  const baseSpeed = Number(baseStats.baseSpeed || baseStats.speed) || 24;
  const baseReaction = Number(baseStats.baseReaction || baseStats.reaction) || 185;

  let clanList = [];
  if (Array.isArray(baseStats.clans) && baseStats.clans.length > 0) {
    clanList = baseStats.clans.map(c => String(c).toLowerCase());
  } else if (baseStats.clan) {
    clanList = String(baseStats.clan).toLowerCase().split(/[+,\/]+/).map(c => c.trim()).filter(Boolean);
  }

  // Если глаза нет или деактивированы
  if (!isEyeActive || !dojutsu || dojutsu === 'none' || dojutsu.id === 'none') {
    // Особый случай для клана Тэнрай: врожденная защита от внезапности 15% работает даже с выключенным глазом!
    const hasTenrai = clanList.some(c => c.includes('тэнрай') || c.includes('тенрай'));
    const passiveForesight = hasTenrai ? 15 : 0;
    return {
      speed: baseSpeed,
      reaction: baseReaction,
      predvidenie: passiveForesight,
      predvideniePercent: passiveForesight,
      accuracyBonus: 0,
      techniqueAmpBonus: 0,
      upkeep: 0,
      speedBonusText: null,
      reactionBonusText: passiveForesight > 0 ? `+${passiveForesight}% (пассивка Тэнрай)` : null
    };
  }

  // Получаем данные додзюцу
  const dojutsuData = typeof dojutsu === 'string'
    ? DOJUTSU_DATABASE[dojutsu] || DOJUTSU_DATABASE.none
    : dojutsu.id && DOJUTSU_DATABASE[dojutsu.id]
      ? DOJUTSU_DATABASE[dojutsu.id]
      : dojutsu;

  const rawPredvidenie = Number(dojutsuData.predvidenie) || 0;
  const rawAccuracy = Number(dojutsuData.accuracy) || 0;
  const rawAmp = Number(dojutsuData.techniqueAmp || dojutsuData.lightningAmp) || 0;
  const speedBonusPct = Number(dojutsuData.speedBonusPercent) || 0;
  const upkeep = Number(dojutsuData.upkeep) || 0;

  // 1. СИНЕРГЕТИЧЕСКИЙ ПОТОЛОК:
  // Если у бойца в родословной есть клан со встроенным телесным бонусом реакции (Сюнрай или Тэнрай, чистый или в смеси)
  // И активно Предвидение додзюцу — итоговое Предвидение умножается на 0.7 (на 30% слабее).
  let effectivePredvidenie = rawPredvidenie;
  const hasSynergyPenalty = clanList.some(c => c.includes('сюнрай') || c.includes('тэнрай') || c.includes('тенрай'));
  if (hasSynergyPenalty && effectivePredvidenie > 0) {
    effectivePredvidenie = Math.round(effectivePredvidenie * 0.7);
  }

  // 2. ВНЕЗАПНЫЕ АТАКИ (СО СПИНЫ):
  // Предвидение глаз = 0%, КРОМЕ Бьякугана (360° обзор) и Тэнрай (пассивная защита 15%).
  if (baseStats.isBackAttack) {
    const hasByakugan = dojutsuData.family === 'Byakugan' || 
      (dojutsuData.activeEyes && dojutsuData.activeEyes.some(e => e.family === 'Byakugan'));
    const hasTenrai = clanList.some(c => c.includes('тэнрай') || c.includes('тенрай'));
    if (hasByakugan) {
      // Бьякуган видит всё на 360°
    } else if (hasTenrai) {
      effectivePredvidenie = Math.min(effectivePredvidenie, 15);
    } else {
      effectivePredvidenie = 0;
    }
  }

  // 3. ГЕНДЗЮЦУ:
  // Пока боец под гендзюцу — Предвидение додзюцу = 0% (кроме Пробуждённого Бьякугана, видящего сквозь любое гендзюцу)
  const isAwakenedByakugan = dojutsuData.id === 'byakugan_awakened' ||
    (dojutsuData.activeEyes && dojutsuData.activeEyes.some(e => e.id === 'byakugan_awakened'));
  if (baseStats.isUnderGenjutsu && !isAwakenedByakugan) {
    effectivePredvidenie = 0;
  }

  // 4. ПОТОЛОК ПРЕДВИДЕНИЯ:
  // Итоговое Предвидение бойца не может быть выше 90%.
  effectivePredvidenie = Math.min(90, Math.max(0, effectivePredvidenie));

  // 5. РАСЧЕТ РЕАКЦИИ В МС:
  // Реакция в бою = baseReaction * (1 - predvidenie / 100)
  const predvidenieFraction = effectivePredvidenie / 100;
  const effectiveReaction = Math.max(20, Math.round(baseReaction * (1 - predvidenieFraction)));
  const reactionDiff = baseReaction - effectiveReaction;

  // 6. РАСЧЕТ ФИЗИЧЕСКОЙ СКОРОСТИ:
  // Суммируются бонусы к скорости от всех активных глаз (Аойган, Икадзутиган)
  let effectiveSpeed = baseSpeed;
  if (speedBonusPct > 0) {
    effectiveSpeed = Math.round(baseSpeed * (1 + speedBonusPct / 100));
  }
  const speedDiff = effectiveSpeed - baseSpeed;

  return {
    speed: effectiveSpeed,
    reaction: effectiveReaction,
    predvidenie: effectivePredvidenie,
    predvideniePercent: effectivePredvidenie,
    accuracyBonus: rawAccuracy,
    techniqueAmpBonus: rawAmp,
    upkeep,
    speedBonusText: speedDiff > 0 ? `+${speedDiff} м/с (+${speedBonusPct}%)` : null,
    reactionBonusText: `−${reactionDiff} мс (${effectivePredvidenie}% предвидения${hasSynergyPenalty ? ', син. потолок ×0.7' : ''})`
  };
}

/**
 * Вспомогательный парсер списка кланов из строки или массива
 */
function parseClansList(clanInput) {
  if (!clanInput) return [];
  if (Array.isArray(clanInput)) {
    return clanInput.map(c => String(c).trim()).filter(Boolean);
  }
  if (typeof clanInput === 'string') {
    return clanInput.split(/[+,\/]+/).map(c => c.trim()).filter(Boolean);
  }
  return [];
}

/**
 * Каноническая генерация глаз по вероятностям Раздела 1 и Раздела 3 правил игры:
 * - В чистой линии: 100% положенный глаз.
 * - В смешанной родословной (2 или 3 клана): КАЖДЫЙ положенный по родословной глаз пробуждается с шансом 70% НЕЗАВИСИМО.
 *   Если ни один не пробудился — назначается один из них.
 * - Риннеган: 12% независимо от клана. При одновременном ВМШ и Риннегане -> Пробуждённая форма Ринненгана.
 * - При нескольких глазах: ВСЕ активны одновременно!
 *   Предвидение, Точность, Усиление = МАКСИМУМ среди активных глаз.
 *   Скорость = СУММИРУЕТСЯ.
 *   Поддержка = СУММИРУЕТСЯ.
 *   Техники всех активных глаз доступны сверх 30 слотов.
 * 
 * @param {string|string[]} clanInput - Название клана или массив кланов в родословной
 * @param {boolean} forceRinnegan - Принудительно выдать Риннеган
 * @param {string} specificDojutsuId - Выбранный пользователем ID глаза ('auto', 'none', etc.)
 * @param {boolean|null} isMixedExplicit - Флаг смешанного клана (если известен)
 */
function generateDojutsu(clanInput = '', forceRinnegan = false, specificDojutsuId = null, isMixedExplicit = null) {
  if (specificDojutsuId && specificDojutsuId !== 'auto') {
    const resolved = resolveMultiDojutsu(specificDojutsuId);
    if (resolved) return resolved;
  }

  const clans = parseClansList(clanInput);
  const isMixed = isMixedExplicit !== null ? isMixedExplicit : (clans.length > 1);

  const rinneganRoll = Math.random() * 100;
  const hasRinnegan = forceRinnegan || (rinneganRoll < 12);

  // Определение потенциальных додзюцу-линий по родословной
  const eligibleLines = [];
  clans.forEach(c => {
    const cl = c.toLowerCase();
    if (cl.includes('учиха') && !eligibleLines.includes('uchiha')) eligibleLines.push('uchiha');
    if (cl.includes('хьюга') && !eligibleLines.includes('hyuga')) eligibleLines.push('hyuga');
    if (cl.includes('кинган') && !eligibleLines.includes('kingan')) eligibleLines.push('kingan');
    if (cl.includes('синкай') && !eligibleLines.includes('shinkai')) eligibleLines.push('shinkai');
    if ((cl.includes('тэнрай') || cl.includes('тенрай')) && !eligibleLines.includes('tenrai')) eligibleLines.push('tenrai');
  });

  // Вспомогательный роллер ступени для конкретной ветки
  const rollStageForLine = (line, isMixedBloodline) => {
    const randRoll = Math.random() * 100; // 30 / 30 / 40%
    const awakenRoll = Math.random() * 100; // 35% пробуждение

    if (line === 'uchiha') {
      let stage = 'sharingan_1';
      if (randRoll >= 60) {
        stage = 'sharingan_3';
        // Шанс Мангёкё: 35% в чистой линии, 25% в смеси (Раздел 1)
        const emsChance = isMixedBloodline ? 25 : 35;
        if (awakenRoll < emsChance) {
          stage = 'mangekyo';
        }
      } else if (randRoll >= 30) {
        stage = 'sharingan_2';
      }
      return { ...DOJUTSU_DATABASE[stage] };
    }

    if (line === 'hyuga') {
      let stage = 'byakugan_1';
      if (randRoll >= 60) {
        stage = 'byakugan_3';
        if (awakenRoll < 35) stage = 'byakugan_awakened';
      } else if (randRoll >= 30) {
        stage = 'byakugan_2';
      }
      return { ...DOJUTSU_DATABASE[stage] };
    }

    if (line === 'kingan') {
      let stage = 'kingan_1';
      if (randRoll >= 60) {
        stage = 'kingan_3';
        if (awakenRoll < 35) stage = 'kingan_awakened';
      } else if (randRoll >= 30) {
        stage = 'kingan_2';
      }
      return { ...DOJUTSU_DATABASE[stage] };
    }

    if (line === 'shinkai') {
      let stage = 'aoigan_1';
      if (randRoll >= 60) {
        stage = 'aoigan_3';
        if (awakenRoll < 35) stage = 'aoigan_awakened';
      } else if (randRoll >= 30) {
        stage = 'aoigan_2';
      }
      return { ...DOJUTSU_DATABASE[stage] };
    }

    if (line === 'tenrai') {
      let stage = 'ikadzutigan_1';
      if (randRoll >= 60) {
        stage = 'ikadzutigan_3';
        if (awakenRoll < 35) stage = 'ikadzutigan_awakened';
      } else if (randRoll >= 30) {
        stage = 'ikadzutigan_2';
      }
      return { ...DOJUTSU_DATABASE[stage] };
    }

    return null;
  };

  const awakenedEyes = [];

  if (!isMixed) {
    // === ЧИСТАЯ ЛИНИЯ (ОДИН КЛАН) ===
    if (eligibleLines.length > 0) {
      const eye = rollStageForLine(eligibleLines[0], false);
      if (eye) awakenedEyes.push(eye);
    }
  } else {
    // === СМЕШАННАЯ РОДОСЛОВНАЯ (2 ИЛИ 3 КЛАНА) ===
    // Каждый положенный додзюцу пробуждается с шансом 70% независимо
    eligibleLines.forEach(line => {
      const roll70 = Math.random() * 100 < 70;
      if (roll70) {
        const eye = rollStageForLine(line, true);
        if (eye) awakenedEyes.push(eye);
      }
    });

    // Если в родословной была хоть одна линия додзюцу, но ни одна не пробудилась — назначаем одну из них!
    if (eligibleLines.length > 0 && awakenedEyes.length === 0) {
      const pickedLine = eligibleLines[Math.floor(Math.random() * eligibleLines.length)];
      const eye = rollStageForLine(pickedLine, true);
      if (eye) awakenedEyes.push(eye);
    }
  }

  // === ОБРАБОТКА РИННЕГАНА (12% шанс любому бойцу) ===
  if (hasRinnegan) {
    // Проверяем: есть ли среди пробужденных глаз Вечный Мангёкё Шаринган?
    const emsIndex = awakenedEyes.findIndex(e => e.id === 'mangekyo');
    if (emsIndex !== -1) {
      // Пробуждённая форма Ринненгана заменяет ВМШ и Риннеган!
      awakenedEyes[emsIndex] = { ...DOJUTSU_DATABASE.rinnegan_awakened };
    } else {
      // Иначе просто добавляем Риннеган к списку активных глаз
      awakenedEyes.push({ ...DOJUTSU_DATABASE.rinnegan });
    }
  }

  // Если ни одного глаза не пробудилось
  if (awakenedEyes.length === 0) {
    return { ...DOJUTSU_DATABASE.none };
  }

  // Если пробудился ровно один глаз
  if (awakenedEyes.length === 1) {
    return awakenedEyes[0];
  }

  return resolveMultiDojutsu(awakenedEyes);
}

/**
 * Преобразует и комбинирует любое количество выбранных додзюцу (массив ID, массив объектов, либо строка с "+")
 * в единый агрегированный объект додзюцу со всеми техниками, пассивками и суммарными статами по правилам Раздела 1 и 3.
 */
function resolveMultiDojutsu(eyeInput) {
  if (!eyeInput) return { ...DOJUTSU_DATABASE.none };

  let eyeIds = [];
  if (Array.isArray(eyeInput)) {
    eyeIds = eyeInput;
  } else if (typeof eyeInput === 'string') {
    eyeIds = eyeInput.split('+').map(s => s.trim()).filter(Boolean);
  } else if (typeof eyeInput === 'object' && eyeInput.id) {
    eyeIds = [eyeInput.id];
  }

  // Фильтруем 'auto' и 'none'
  const cleanIds = eyeIds.filter(id => id && id !== 'auto' && id !== 'none');
  if (cleanIds.length === 0) {
    if (eyeIds.includes('none')) return { ...DOJUTSU_DATABASE.none };
    return null; // сигнал, что нужен ролл (auto)
  }

  // Находим объекты каждого глаза в DOJUTSU_DATABASE
  let eyeObjs = cleanIds.map(item => {
    if (typeof item === 'object' && item.id) {
      return DOJUTSU_DATABASE[item.id] ? { ...DOJUTSU_DATABASE[item.id] } : item;
    }
    return DOJUTSU_DATABASE[item] ? { ...DOJUTSU_DATABASE[item] } : null;
  }).filter(Boolean);

  if (eyeObjs.length === 0) {
    return { ...DOJUTSU_DATABASE.none };
  }

  // Обработка синергии ВМШ + Риннеган -> Пробуждённая форма Риннегана
  const hasEMS = eyeObjs.some(e => e.id === 'mangekyo');
  const hasRinne = eyeObjs.some(e => e.id === 'rinnegan');
  if (hasEMS && hasRinne) {
    eyeObjs = eyeObjs.filter(e => e.id !== 'mangekyo' && e.id !== 'rinnegan');
    eyeObjs.push({ ...DOJUTSU_DATABASE.rinnegan_awakened });
  }

  if (eyeObjs.length === 1) {
    return eyeObjs[0];
  }

  // Комбинация любого количества активных глаз:
  // Предвидение, Точность, Усиление, Скорость — МАКСИМУМ из активных (бонусы глаз НЕ суммируются между собой!).
  // Поддержка — СУММИРУЕТСЯ.
  // Все техники и пассивки доступны одновременно сверх 30 слотов.
  const maxPredvidenie = Math.max(...eyeObjs.map(e => Number(e.predvidenie) || 0));
  const maxAccuracy = Math.max(...eyeObjs.map(e => Number(e.accuracy) || 0));
  const maxAmp = Math.max(...eyeObjs.map(e => Number(e.techniqueAmp || e.lightningAmp) || 0));
  const maxSpeed = Math.max(...eyeObjs.map(e => Number(e.speedBonusPercent) || 0));
  const sumUpkeep = eyeObjs.reduce((s, e) => s + (Number(e.upkeep) || 0), 0);

  // Сбор уникальных пассивок
  const passivesSet = new Set();
  eyeObjs.forEach(e => {
    (e.passives || []).forEach(p => passivesSet.add(p));
  });

  // Сбор уникальных техник глаз
  const jutsuMap = new Map();
  eyeObjs.forEach(e => {
    (e.jutsu || []).forEach(j => {
      const key = j.id || j.name;
      if (!jutsuMap.has(key)) {
        jutsuMap.set(key, j);
      }
    });
  });

  const eyeNames = eyeObjs.map(e => e.name).join(' + ');
  const stageNames = eyeObjs.map(e => e.stageName || e.name).join(' / ');

  return {
    id: `hybrid_eyes_${eyeObjs.map(e => e.id).join('_')}`,
    name: eyeNames,
    family: 'Hybrid',
    stageName: stageNames,
    isMultiEye: true,
    activeEyes: eyeObjs,
    predvidenie: maxPredvidenie,
    accuracy: maxAccuracy,
    techniqueAmp: maxAmp,
    speedBonusPercent: maxSpeed,
    upkeep: sumUpkeep,
    description: `Сверхредкое наследие смешанной крови: активны одновременно [${eyeNames}]. Все техники доступны, поддержка суммируется (${sumUpkeep.toLocaleString()} ед./ход).`,
    passives: Array.from(passivesSet),
    jutsu: Array.from(jutsuMap.values())
  };
}

